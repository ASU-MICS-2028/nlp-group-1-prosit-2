"""S5.5: the tables and charts for Section B and the slides, from saved results only. Free.
Writes eval/results/tables.md and eval/results/charts/*.png.

    uv run --with matplotlib python -m eval.experiments.report_tables
"""

import json
import pathlib

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt

R = pathlib.Path("eval/results")
read = lambda name: json.loads((R / name).read_text())
BLUE, ORANGE, SURFACE, INK, MUTED = "#2a78d6", "#eb6834", "#fcfcfb", "#0b0b0b", "#52514e"
plt.rcParams.update({"figure.facecolor": SURFACE, "axes.facecolor": SURFACE, "text.color": INK, "axes.labelcolor": MUTED, "font.size": 11,
                     "xtick.color": MUTED, "ytick.color": INK, "axes.spines.top": False, "axes.spines.right": False, "axes.spines.left": False,
                     "axes.edgecolor": "#c9c8c2", "savefig.dpi": 200, "savefig.bbox": "tight"})
(R / "charts").mkdir(exist_ok=True)

abl, vs, full = read("ablations.json"), read("agent_vs_baseline.json"), read("full_system.json")
base = abl["full system (3 runs)"]
rows = [("Full system: questions, no plan (3 runs)", base["percent"], base["percent_without_school"], base["usd"], base["kept_data"], None)]
rows += [(s["label"], s["percent"], s["percent_without_school"], round(s["build_usd"] + s["questions_and_plan_usd"], 2), s["kept_data"], s["average_seconds"])
         for s in abl["setups"].values()]
rows.sort(key=lambda r: r[1])

fig, ax = plt.subplots(figsize=(9, 4.6))
y = range(len(rows))
ax.barh([i + 0.2 for i in y], [r[1] for r in rows], 0.36, color=BLUE, label="All 15 tasks")
ax.barh([i - 0.2 for i in y], [r[2] for r in rows], 0.36, color=ORANGE, label="School task left out")
for i, r in enumerate(rows):
    ax.text(r[1] + 0.8, i + 0.2, f"{r[1]:.1f}", va="center", color=INK, fontsize=10)
ax.set_yticks(list(y), [r[0] for r in rows])
ax.set(xlim=(0, 108), xlabel="Hidden tests passed (%)")
ax.tick_params(axis="y", length=0)
ax.xaxis.grid(True, color="#e8e7e1")
ax.set_axisbelow(True)
ax.legend(frameon=False, loc="lower left", bbox_to_anchor=(0, 1), ncols=2)
ax.set_title("What each part of the system is worth", loc="left", fontweight="bold", pad=34)
fig.savefig(R / "charts/setups_score.png")

by_cost = sorted(rows, key=lambda r: r[3])
fig, ax = plt.subplots(figsize=(9, 3.8))
ax.barh([r[0] for r in by_cost], [r[3] for r in by_cost], 0.6, color=BLUE)
for i, r in enumerate(by_cost):
    ax.text(r[3] + 0.05, i, f"${r[3]:.2f}", va="center", color=INK, fontsize=10)
ax.set(xlabel="Cost of building all 15 tasks (US$)", xlim=(0, 4.7))
ax.tick_params(axis="y", length=0)
ax.xaxis.grid(True, color="#e8e7e1")
ax.set_axisbelow(True)
ax.set_title("What each setup costs", loc="left", fontweight="bold")
fig.savefig(R / "charts/setups_cost.png")

fig, ax = plt.subplots(figsize=(7, 3))
sides = [("One Claude call (4 rounds)", vs["every test"]["one call"]), ("The agent (3 runs)", vs["every test"]["agent"])]
for i, (label, s) in enumerate(sides):
    ax.barh(i, s["average"], 0.5, color=BLUE)
    ax.plot([s["lowest"], s["highest"]], [i, i], color=INK, lw=2)
    ax.text(s["highest"] + 1, i, f"{s['average']:.1f}%", va="center", color=INK)
ax.set_yticks([0, 1], [c[0] for c in sides])
ax.set(xlim=(0, 108), xlabel="Hidden tests passed (%). The line shows the lowest and highest run")
ax.tick_params(axis="y", length=0)
ax.xaxis.grid(True, color="#e8e7e1")
ax.set_axisbelow(True)
ax.set_title("The agent against one Claude call", loc="left", fontweight="bold")
fig.savefig(R / "charts/agent_vs_one_call.png")

md = ["# Tables for the report", "", "Generated by `eval/experiments/report_tables.py` from the saved results. Do not edit by hand.", "",
      "## The agent against one Claude call", "", "| | Agent (3 runs) | One call (4 rounds) |", "|---|---|---|"]
md += [f"| {k.capitalize()} | {v['agent']['average']}% ({v['agent']['lowest']} to {v['agent']['highest']}) | {v['one call']['average']}% ({v['one call']['lowest']} to {v['one call']['highest']}) |" for k, v in vs.items()]
md += ["", "## Each setup, on all 15 tasks", "", "One build per setup, scored 3 times. Gaps under about 2 points are noise. " + "The school task is shown both ways because one choice in a build moves it by 10 tests.", "",
       "| Setup | All tasks | School left out | Keeps data | Cost to build all 15 | Seconds per build |", "|---|---|---|---|---|---|"]
md += [f"| {r[0]} | {r[1]}% | {r[2]}% | {r[4]} | ${r[3]:.2f} | {r[5] if r[5] else '37'} |" for r in sorted(rows, key=lambda r: -r[1])]
md += ["", "Keeps data counts only builds where the check could run: a build that refuses new records cannot be checked. No build that could be checked lost its data. " "The local Qwen model was not rerun: `harness/s39_qwen` 0%, `harness/s39_qwen_search` 59.0% on 5 easy tasks, the other 10 did not run.",
       "", "## The full system, per task (3 builds, tests passed)", "", "| Task | Tests | Run 1 | Run 2 | Run 3 | Average cost | Average build time |", "|---|---|---|---|---|---|---|"]
for t in full["tasks"]:
    v = list(t["runs"].values())
    md.append(f"| {t['task']} | {t['tests']} | {v[0]['passed']} | {v[1]['passed']} | {v[2]['passed']} | ${sum(x['usd'] for x in v) / 3:.2f} | {sum(x['build_seconds'] for x in v) / 3:.0f} s |")
(R / "tables.md").write_text("\n".join(md) + "\n")
